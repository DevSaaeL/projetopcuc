CREATE TABLE perfis (codigo VARCHAR(30) PRIMARY KEY);
INSERT INTO perfis VALUES ('MASTER_ADMIN'),('ADMIN'),('SUPORTE'),('USUARIO');
CREATE TABLE filiais (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(160) NOT NULL, cidade VARCHAR(120) NOT NULL, estado VARCHAR(2) NOT NULL,
 endereco VARCHAR(300) NOT NULL DEFAULT '', responsavel VARCHAR(160) NOT NULL DEFAULT '', telefone VARCHAR(40) NOT NULL DEFAULT '',
 ativo BOOLEAN NOT NULL DEFAULT TRUE, criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE usuarios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(160) NOT NULL, email VARCHAR(200) NOT NULL UNIQUE, senha_hash VARCHAR(100) NOT NULL,
 perfil VARCHAR(30) NOT NULL REFERENCES perfis(codigo), filial_id BIGINT REFERENCES filiais(id),
 telefone VARCHAR(40) NOT NULL DEFAULT '', setor VARCHAR(100) NOT NULL DEFAULT '', ativo BOOLEAN NOT NULL DEFAULT TRUE,
 versao_sessao INT NOT NULL DEFAULT 0, preferencias VARCHAR(2000) NOT NULL DEFAULT '{}',
 criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (perfil = 'MASTER_ADMIN' OR filial_id IS NOT NULL)
);
CREATE TABLE qrcodes (
 id VARCHAR(36) PRIMARY KEY, nome VARCHAR(160) NOT NULL, filial_id BIGINT NOT NULL REFERENCES filiais(id),
 bloco VARCHAR(80) NOT NULL, sala VARCHAR(80) NOT NULL, descricao VARCHAR(300) NOT NULL DEFAULT '',
 ativo BOOLEAN NOT NULL DEFAULT TRUE, criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE chamados (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, titulo VARCHAR(150) NOT NULL, descricao VARCHAR(2000) NOT NULL,
 solicitante_id BIGINT NOT NULL REFERENCES usuarios(id), filial_id BIGINT NOT NULL REFERENCES filiais(id),
 cidade VARCHAR(120) NOT NULL, bloco VARCHAR(80) NOT NULL DEFAULT '', sala VARCHAR(80) NOT NULL DEFAULT '',
 setor VARCHAR(100) NOT NULL DEFAULT '', categoria VARCHAR(80) NOT NULL DEFAULT '', tipo_atendimento VARCHAR(40) NOT NULL DEFAULT 'incidente',
 prioridade VARCHAR(10) NOT NULL CHECK (prioridade IN ('BAIXA','MEDIA','ALTA','CRITICA')),
 status VARCHAR(30) NOT NULL DEFAULT 'ABERTO' CHECK (status IN ('ABERTO','EM_ATENDIMENTO','AGUARDANDO_USUARIO','FINALIZADO','CANCELADO')),
 tecnico_id BIGINT REFERENCES usuarios(id), abertura TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 atendimento TIMESTAMP WITH TIME ZONE, finalizacao TIMESTAMP WITH TIME ZONE,
 sla_resposta INT NOT NULL, sla_resolucao INT NOT NULL, origem VARCHAR(10) NOT NULL, qr_id VARCHAR(36) REFERENCES qrcodes(id),
 solucao VARCHAR(2000) NOT NULL DEFAULT ''
);
CREATE TABLE mensagens (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, chamado_id BIGINT NOT NULL REFERENCES chamados(id),
 autor_id BIGINT NOT NULL REFERENCES usuarios(id), mensagem VARCHAR(4000) NOT NULL,
 criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE notificacoes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
 chamado_id BIGINT NOT NULL REFERENCES chamados(id), tipo VARCHAR(40) NOT NULL, titulo VARCHAR(160) NOT NULL,
 lida BOOLEAN NOT NULL DEFAULT FALSE, criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE auditoria (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, autor_id BIGINT NOT NULL REFERENCES usuarios(id),
 chamado_id BIGINT REFERENCES chamados(id), acao VARCHAR(80) NOT NULL, descricao VARCHAR(2000) NOT NULL,
 criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE anexos (
 id VARCHAR(36) PRIMARY KEY, chamado_id BIGINT NOT NULL REFERENCES chamados(id), autor_id BIGINT NOT NULL REFERENCES usuarios(id),
 nome VARCHAR(255) NOT NULL, tamanho BIGINT NOT NULL, conteudo BYTEA NOT NULL,
 criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX chamados_filial_status ON chamados(filial_id,status);
CREATE INDEX chamados_solicitante ON chamados(solicitante_id);
CREATE INDEX mensagens_chamado ON mensagens(chamado_id,id);
CREATE INDEX notificacoes_usuario ON notificacoes(usuario_id,lida);
CREATE INDEX auditoria_chamado ON auditoria(chamado_id,id);
