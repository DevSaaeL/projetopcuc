CREATE TABLE blocos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 filial_id BIGINT NOT NULL REFERENCES filiais(id),
 nome VARCHAR(80) NOT NULL,
 nome_chave VARCHAR(80) NOT NULL,
 ativo BOOLEAN NOT NULL DEFAULT TRUE,
 UNIQUE(filial_id,nome_chave)
);
CREATE TABLE usuario_blocos (
 usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
 bloco_id BIGINT NOT NULL REFERENCES blocos(id),
 PRIMARY KEY(usuario_id,bloco_id)
);
