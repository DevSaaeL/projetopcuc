SELECT c.id,c.tecnico_id,t.nome,(SELECT a.autor_id FROM auditoria a WHERE a.chamado_id=c.id AND a.acao=c.status ORDER BY a.id DESC LIMIT 1),(SELECT COALESCE(a.autor_nome,au.nome) FROM auditoria a LEFT JOIN usuarios au ON au.id=a.autor_id WHERE a.chamado_id=c.id AND a.acao=c.status ORDER BY a.id DESC LIMIT 1),c.filial_id,f.nome,c.titulo,c.descricao,COALESCE(c.solicitante_nome,u.nome,'Não informado'),u.email,u.telefone,c.cidade,c.bloco,c.sala,c.setor,c.categoria,c.prioridade,c.status,c.abertura,c.inicio_ciclo,c.atendimento,COALESCE(c.finalizacao,c.abertura),c.sla_resposta,c.sla_resolucao,c.solucao,COALESCE((SELECT MAX(a.id) FROM auditoria a WHERE a.chamado_id=c.id),0),(c.finalizacao IS NULL)
