CREATE TABLE atendimentos_chamado (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 chamado_id BIGINT NOT NULL REFERENCES chamados(id),
 tecnico_id BIGINT REFERENCES usuarios(id),
 tecnico_nome VARCHAR(160),
 finalizado_por_id BIGINT REFERENCES usuarios(id),
 finalizado_por_nome VARCHAR(160),
 filial_id BIGINT NOT NULL REFERENCES filiais(id),
 filial_nome VARCHAR(160) NOT NULL,
 titulo VARCHAR(150) NOT NULL,
 descricao VARCHAR(2000) NOT NULL,
 solicitante_nome VARCHAR(160),
 solicitante_email VARCHAR(200),
 solicitante_telefone VARCHAR(40),
 cidade VARCHAR(120) NOT NULL,
 bloco VARCHAR(80),
 sala VARCHAR(80),
 setor VARCHAR(100),
 categoria VARCHAR(80),
 prioridade VARCHAR(10) NOT NULL,
 status VARCHAR(30) NOT NULL CHECK (status IN ('FINALIZADO','CANCELADO')),
 abertura TIMESTAMP WITH TIME ZONE NOT NULL,
 inicio_ciclo TIMESTAMP WITH TIME ZONE,
 atendimento TIMESTAMP WITH TIME ZONE,
 finalizacao TIMESTAMP WITH TIME ZONE NOT NULL,
 sla_resposta INT NOT NULL,
 sla_resolucao INT NOT NULL,
 solucao VARCHAR(2000) NOT NULL,
 ultimo_evento_id BIGINT NOT NULL DEFAULT 0,
 encerramento_estimado BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX atendimentos_tecnico_data ON atendimentos_chamado(tecnico_id,finalizacao,id);
CREATE INDEX atendimentos_filial_data ON atendimentos_chamado(filial_id,finalizacao,id);
CREATE TABLE atendimento_anexos (
 atendimento_id BIGINT NOT NULL REFERENCES atendimentos_chamado(id),
 anexo_id VARCHAR(36) NOT NULL REFERENCES anexos(id),
 PRIMARY KEY(atendimento_id,anexo_id)
);

